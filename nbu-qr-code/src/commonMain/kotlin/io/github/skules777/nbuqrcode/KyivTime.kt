package io.github.skules777.nbuqrcode

/**
 * Момент часу як 12 цифр `РРММДДГГХХСС` за київським часом (поля 15–16).
 *
 * Поля 15–16 кодуються без будь-якої позначки часового поясу, тож обидві сторони
 * мусять мовчки припускати один і той самий пояс. Для внутрішньоукраїнського
 * стандарту це київський час — і це не налаштування, а частина інтерпретації
 * формату. Пояс пристрою тут був би пасткою: бекенд у Docker (типово UTC) записав
 * би термін дії на 2–3 години раніше, ніж задумав отримувач, а QR при цьому
 * лишався б валідним на вигляд. Перевірено сканером — monobank і Sense Bank
 * справді відхиляють протермінований код.
 *
 * Пояс шукається як `Europe/Kyiv`, потім `Europe/Kiev` (до tzdata 2022b існувала
 * лише ця назва), і лише тоді — фіксоване UTC+2 без літнього часу.
 */
internal expect fun kyivDateTimeDigits(epochSeconds: Long): String

internal fun pad2(value: Int): String = value.toString().padStart(2, '0')
