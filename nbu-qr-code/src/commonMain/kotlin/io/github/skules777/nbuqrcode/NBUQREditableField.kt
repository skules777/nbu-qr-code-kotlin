package io.github.skules777.nbuqrcode

/**
 * Поля структури даних QR-коду, які "Код заборони зміни полів" (поле 14,
 * додаток 4, п. 4.14) може окремо дозволити платнику змінювати. Решту полів
 * (1–5, 11, 14–17) стандарт блокує завжди, тож значень для них тут немає; до
 * того ж для полів 16–17 немає й біта: маска з 4 hex-символів має лише 16 бітів,
 * тобто адресує поля до №15.
 *
 * Біт поля — `1 shl <номер поля з таблиці 2>`, і це перевірено на реальних
 * застосунках, а не лише прочитано з тексту Правил. Текст каже "номер поля
 * відповідає номеру біта, починаючи з наймолодшого"; буквально це ставить поле 8
 * на біт 7, і тоді власний приклад Правил (маска `FEFF` з підписом "дозволено
 * змінювати суму", поле 8) розкодувався б як поле 9. Приват24 і monobank
 * незалежно один від одного для `FEFF` розблоковують саме *суму*, тобто біт 8
 * (`0x100`) — це `1 shl номер поля`, на біт вище за буквальне прочитання. Тип
 * кодує саме цей емпіричний результат; наймолодший біт (`1 shl 0`) через це не
 * належить жодному полю.
 */
public enum class NBUQREditableField(internal val bit: Int) {
    /** Поле 6 — Отримувач. */
    RECIPIENT(1 shl 6),

    /** Поле 7 — Рахунок отримувача. */
    IBAN(1 shl 7),

    /** Поле 8 — Сума / валюта. */
    AMOUNT(1 shl 8),

    /** Поле 9 — Код отримувача. */
    RECIPIENT_CODE(1 shl 9),

    /** Поле 10 — Категорія / ціль. */
    CATEGORY(1 shl 10),

    /** Поле 12 — Призначення платежу. */
    PURPOSE(1 shl 12),

    /** Поле 13 — Відображення (дисплей). */
    DISPLAY_TEXT(1 shl 13),
}

internal object NBUQRLockMask {
    /**
     * Hex-рядок поля 14 (`lock_mask`), що блокує всі поля, крім переданих. Поля,
     * які стандарт забороняє змінювати завжди, лишаються заблокованими за будь-якої
     * множини: жодне значення [NBUQREditableField] не відповідає їхнім бітам.
     */
    fun hex(editable: Set<NBUQREditableField>): String {
        val mask = editable.fold(0) { bits, field -> bits or field.bit }.inv() and 0xFFFF
        return mask.toString(16).uppercase().padStart(4, '0')
    }
}
